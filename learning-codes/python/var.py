#variable is a container that holds data. 
# In Python, you can create a variable by assigning a value to it using the equals sign (=). For example:

x = 5
y = "Hello, World!"
z = 3.14

# In this example, we have created three variables: x, y, and z.

print(x) # this will print the value of x, which is 5
print(y) # this will print the value of y, which is "Hello, World!"
print(z) # this will print the value of z, which is 3.14
