import numpy as np

#scalar multiplication

array =np.array([1, 2, 3])

print (array + 1) #array addition every element of the array is added by 1

print (array * 2) #array multiplication every element of the array is multiplied by 2

print (array - 1) #array subtraction every element of the array is subtracted by 1

print (array / 2) #array division every element of the array is divided by 2

print (array ** 2) #array exponentiation every element of the array is raised to the power of 2

arr=np.array([1.01, 2.005, 3.555786])

print (np.round(arr)) #array round every element of the array is rounded to the nearest integer)) 

print (np.floor(arr)) #array floor every element of the array is rounded down to the nearest integer

print (np.ceil(arr)) #array ceil every element of the array is rounded up to the nearest integer

print(np.pi) #prints the value of pi
